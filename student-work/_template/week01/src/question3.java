public class Question3 {
    public static void main(String[] args) {

        int product   = 4 * 3;   // 4 times 3 = 12
        int quotient  = 10 / 3;  // 10 divided by 3 = 3 (drops the decimal)
        int remainder = 10 % 3;  // 10 divided by 3 remainder = 1

        // Print all values
        System.out.println("product   = " + product);    // 12
        System.out.println("quotient  = " + quotient);   // 3
        System.out.println("remainder = " + remainder);  // 1
        System.out.println(17 % 2);                      // 1, so 17 is odd
    }
}
