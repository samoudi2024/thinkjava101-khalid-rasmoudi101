public class Question6 {
    public static void main(String[] args) {

        int score = 85;  // integer variable storing the value 85

        // Comparison operators
        System.out.println(score >= 70);  // true  (85 is greater than or equal to 70)
        System.out.println(score < 60);   // false (85 is not less than 60)

        // instanceof operator
        Object value = "Java";            // Object variable storing the String "Java"
        System.out.println(value instanceof String); // true ("Java" is a String)
    }
}
